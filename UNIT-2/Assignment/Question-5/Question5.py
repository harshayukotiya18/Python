# 5. Write a Python program to accept a sentence from the user and perform the following
# operations:
# Remove leading and trailing spaces using lstrip(), rstrip(), and strip().

a=(input("Enter a Sentences:"))

print("Original String:", a)
print("After using lstrip():", a.lstrip())
print("After using rstrip():", a.rstrip())
print("After using strip():", a.strip())

